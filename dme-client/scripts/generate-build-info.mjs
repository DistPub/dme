#!/usr/bin/env node
/**
 * scripts/generate-build-info.mjs - 构建时生成 src/generated/build-info.ts。
 *
 * 把当前 commit sha / 工作区是否 dirty / 构建时间写进一个被 .gitignore 的
 * 生成文件，设置页最底部展示，用于多端测试时快速对齐各设备跑的是哪个
 * 构建（防止 web 缓存导致的旧 bundle 版本误导）。
 *
 * 由以下入口调用（勿手工运行也可，文件缺失时 tsc 会缺导入）：
 *   - dme-client: package.json 的 dev / build:web 前置
 *   - dme-miniapp: deploy.mjs cmdBuild + package.json 的 build:weapp /
 *     dev:weapp / typecheck 前置
 */

import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT = resolve(ROOT, 'src/generated/build-info.ts');

function git(args) {
  return execSync(`git ${args}`, { cwd: ROOT, encoding: 'utf8' }).trim();
}

let sha = 'unknown';
let dirty = false;
try {
  sha = git('rev-parse --short HEAD');
  dirty = git('status --porcelain').length > 0;
} catch (err) {
  console.warn('⚠️  git 信息读取失败，build-info 将写 unknown:', err.message);
}

const time = new Date().toISOString();

const content = `// AUTO-GENERATED by scripts/generate-build-info.mjs — 请勿手工编辑。
// 构建时写入当前 commit 信息，设置页最底部展示（多端测试对版本用）。
export const BUILD_COMMIT_SHA = '${sha}';
export const BUILD_DIRTY = ${dirty ? 'true' : 'false'};
export const BUILD_TIME = '${time}';
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, content, 'utf8');
console.log(`✅ build-info: ${sha}${dirty ? ' (dirty)' : ''} @ ${time}`);
